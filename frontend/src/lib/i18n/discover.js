// "zh-CN", "pt-BR" ou "fr-FR" / "en" / "zh" -> code connu
export function normLang(x) {
  const s = String(x || "fr");
  if (TEXTS[s]) return s;
  const low = s.toLowerCase();
  if (low.startsWith("zh")) return "zh-CN";
  if (low.startsWith("pt")) return "pt-BR";
  const base = low.split(/[-_]/)[0];
  return TEXTS[base] ? base : "fr";
}

export function dtext(lang, key, vars) {
  const l = normLang(lang);
  let s = TEXTS[l]?.[key] ?? TEXTS.en[key] ?? TEXTS.fr[key] ?? key;
  if (vars) for (const k of Object.keys(vars)) s = s.replaceAll(`{${k}}`, vars[k]);
  return s;
}

export function tagLabel(lang, tag) {
  const l = normLang(lang);
  return TAG_LABELS[l]?.[tag] || TAG_LABELS.en[tag] || tag;
}

// Nom du mois dans la langue (sans tableau à maintenir)
export function monthName(lang, m, style = "long") {
  try {
    return new Intl.DateTimeFormat(normLang(lang), { month: style, timeZone: "UTC" }).format(new Date(Date.UTC(2026, m - 1, 15)));
  } catch {
    return String(m);
  }
}
